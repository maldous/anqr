#!/usr/bin/env node

/**
 * notify.mjs — Notification dispatch
 *
 * Sends summary notifications after harness/guardian runs.
 *
 * Channels:
 *   stdout  — always (for systemd journal capture)
 *   linear  — post comment on Symphony parent issue (requires LINEAR_API_KEY)
 *
 * Input:
 *   Reads reports/latest.json for harness summary.
 *
 * Usage:
 *   node scripts/ops/notify.mjs --channel=stdout
 *   LINEAR_API_KEY=... node scripts/ops/notify.mjs --channel=linear
 *   LINEAR_API_KEY=... node scripts/ops/notify.mjs --channel=all
 *   node scripts/ops/notify.mjs --channel=stdout --dry-run
 *
 * Exit code:
 *   0 = notification sent
 *   1 = error reading report or sending notification
 */

import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const ROOT = resolve(__dirname, '..', '..');
const REPORT_PATH = resolve(ROOT, 'reports/latest.json');

const SYMPHONY_PARENT_ID = '6e46dabb-652f-4594-a01f-978fc96dbbe9';

function parseArgs() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const channelArg = args.find((a) => a.startsWith('--channel='));
  const channel = channelArg ? channelArg.split('=')[1] : 'stdout';
  return { dryRun, channel };
}

function formatSummary(report) {
  const { profile, timestamp, total_duration_ms, summary, checks } = report;
  const failures = checks.filter((c) => !c.pass);
  const passes = checks.filter((c) => c.pass);
  const timing = (total_duration_ms / 1000).toFixed(1);

  const lines = [
    `## Nightly Harness Report`,
    '',
    `**Profile:** ${profile}`,
    `**Timestamp:** ${timestamp}`,
    `**Duration:** ${timing}s`,
    `**Result:** ${summary.passed}/${summary.total} passed, ${summary.failed} failed`,
    '',
  ];

  if (failures.length > 0) {
    lines.push('### ❌ Failures', '');
    for (const check of failures) {
      const t = check.duration_ms > 1000
        ? `${(check.duration_ms / 1000).toFixed(1)}s`
        : `${check.duration_ms}ms`;
      lines.push(`- **${check.name}** (${t}): ${check.detail.split('\n')[0]}`);
    }
    lines.push('');
  }

  if (passes.length > 0) {
    lines.push('### ✅ Passed', '');
    for (const check of passes) {
      lines.push(`- ${check.name}`);
    }
    lines.push('');
  }

  lines.push('---', '*Generated by notify.mjs*');
  return lines.join('\n');
}

function formatStdout(report) {
  const { profile, timestamp, total_duration_ms, summary, checks } = report;
  const timing = (total_duration_ms / 1000).toFixed(1);

  const lines = [
    `[notify] Harness report summary`,
    `[notify] Profile: ${profile} | Time: ${timestamp} | Duration: ${timing}s`,
    `[notify] Result: ${summary.passed}/${summary.total} passed, ${summary.failed} failed`,
    '',
  ];

  for (const check of checks) {
    const icon = check.pass ? '✅' : '❌';
    const t = check.duration_ms > 1000
      ? `${(check.duration_ms / 1000).toFixed(1)}s`
      : `${check.duration_ms}ms`;
    lines.push(`  ${icon} ${check.name} (${t})`);
  }

  return lines.join('\n');
}

async function notifyLinear(report, dryRun) {
  const apiKey = process.env.LINEAR_API_KEY;
  if (!apiKey) {
    console.log('[notify] LINEAR_API_KEY not set — skipping Linear notification');
    return;
  }

  const body = formatSummary(report);

  if (dryRun) {
    console.log('[notify] [DRY RUN] Would post Linear comment on ANQ-364');
    console.log('[notify] [DRY RUN] Comment preview (first 200 chars):');
    console.log(body.slice(0, 200) + '...');
    return;
  }

  const { addComment } = await import('./linear-client.mjs');
  await addComment(SYMPHONY_PARENT_ID, body);
  console.log('[notify] Posted summary to Linear (ANQ-364)');
}

async function main() {
  const { dryRun, channel } = parseArgs();

  console.log(`[notify]${dryRun ? ' (DRY RUN)' : ''} channel=${channel}\n`);

  if (!existsSync(REPORT_PATH)) {
    console.error(`[notify] No report found at ${REPORT_PATH}`);
    console.error('[notify] Run harness-report.mjs first.');
    process.exit(1);
  }

  const report = JSON.parse(readFileSync(REPORT_PATH, 'utf-8'));

  // stdout channel (always available)
  if (channel === 'stdout' || channel === 'all') {
    console.log(formatStdout(report));
  }

  // Linear channel
  if (channel === 'linear' || channel === 'all') {
    await notifyLinear(report, dryRun);
  }

  console.log('\n[notify] done');
  process.exit(0);
}

main();
