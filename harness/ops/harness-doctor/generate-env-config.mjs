import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";

import { parseEnvKeys } from "./parse-env-keys.mjs";
import { defaultSurfaces } from "./default-surfaces.mjs";

/**
 * Single-authoritative-source config generation and validation.
 *
 * The repo template `services/systemd/anqr-ops.env` is the single source
 * of truth for the env key inventory. This function validates or generates
 * all host-local env surfaces from that template.
 *
 * Modes:
 * - "validate": compare all surfaces against template, report drift
 * - "generate": create/update surface files to match template key inventory
 *
 * NEVER reads or writes secret values. Only operates on key names.
 *
 * @param {object} [opts]
 * @param {"validate" | "generate"} [opts.mode]
 * @param {string} [opts.templatePath]
 * @param {Array<{name: string, path: string}>} [opts.surfaces]
 * @param {boolean} [opts.dryRun] — generate mode: report without writing
 * @returns {Promise<{pass: boolean, detail: string, templateKeyCount: number, surfaces: Array, actions: string[]}>}
 */
export async function generateEnvConfig({
  mode = "validate",
  templatePath: templatePathOverride,
  surfaces: surfacesOverride,
  dryRun = false,
} = {}) {
  let templatePath = templatePathOverride;
  if (!templatePath) {
    const { ROOT } = await import("./root.mjs");
    templatePath = resolve(ROOT, "services/systemd/anqr-ops.env");
  }
  const surfaces = surfacesOverride || defaultSurfaces();
  const actions = [];

  if (!existsSync(templatePath)) {
    return {
      pass: false,
      detail: `Authoritative template missing: ${templatePath}`,
      templateKeyCount: 0,
      surfaces: [],
      actions: [],
    };
  }

  const templateKeys = parseEnvKeys(templatePath);
  const templateKeySet = new Set(templateKeys);
  const surfaceResults = [];

  for (const surface of surfaces) {
    const exists = existsSync(surface.path);
    const surfaceKeys = exists ? parseEnvKeys(surface.path) : [];
    const surfaceKeySet = new Set(surfaceKeys);

    const missingKeys = templateKeys.filter((k) => !surfaceKeySet.has(k));
    const extraKeys = surfaceKeys.filter((k) => !templateKeySet.has(k));

    surfaceResults.push({
      name: surface.name,
      path: surface.path,
      exists,
      keyCount: surfaceKeys.length,
      missingKeys,
      extraKeys,
    });

    if (mode === "generate" && !dryRun) {
      if (!exists) {
        mkdirSync(dirname(surface.path), { recursive: true });
        const content =
          `# Generated by generate-env-config from ${templatePath}\n` +
          `# Populate with real values — this file only contains key names.\n\n` +
          templateKeys.map((k) => `${k}=`).join("\n") +
          "\n";
        writeFileSync(surface.path, content, "utf-8");
        actions.push(`Created ${surface.name} (${surface.path}) with ${templateKeys.length} keys`);
      } else if (missingKeys.length > 0) {
        const existing = readFileSync(surface.path, "utf-8");
        const additions = missingKeys
          .map((k) => `# auto-generated by generate-env-config\n${k}=`)
          .join("\n");
        writeFileSync(surface.path, existing.trimEnd() + "\n\n" + additions + "\n", "utf-8");
        actions.push(
          `Appended ${missingKeys.length} missing keys to ${surface.name}: ${missingKeys.join(", ")}`,
        );
      }
    } else if (mode === "generate" && dryRun) {
      if (!exists) {
        actions.push(
          `Would create ${surface.name} (${surface.path}) with ${templateKeys.length} keys`,
        );
      } else if (missingKeys.length > 0) {
        actions.push(
          `Would append ${missingKeys.length} missing keys to ${surface.name}: ${missingKeys.join(", ")}`,
        );
      }
    }
  }

  const hasMissingKeys = surfaceResults.some((s) => s.missingKeys.length > 0);
  const hasMissingSurface = surfaceResults.some((s) => !s.exists);
  const pass = !hasMissingKeys && !hasMissingSurface;

  let detail;
  if (pass) {
    detail = `All ${surfaceResults.length} config surfaces aligned with template (${templateKeys.length} keys)`;
  } else {
    const issues = [];
    for (const s of surfaceResults) {
      if (!s.exists) issues.push(`${s.name}: file missing`);
      else if (s.missingKeys.length > 0)
        issues.push(`${s.name}: missing ${s.missingKeys.length} keys`);
    }
    detail = issues.join("; ");
  }

  return {
    pass,
    detail,
    templateKeyCount: templateKeys.length,
    surfaces: surfaceResults,
    actions,
  };
}
